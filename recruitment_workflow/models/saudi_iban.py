# -*- coding: utf-8 -*-
"""التحقق من الآيبان السعودي - مشترك بين طلب التوظيف والسلفة (السداد
البنكي يعتمد على هذا الموديول).

لا نعتمد base_iban: غير مثبَّت، ويتحقق من صيغ كل الدول - بينما المطلوب
هنا آيبان سعودي تحديداً (خطأ رقم واحد يعني تحويلاً فاشلاً أو لحساب آخر).
"""
import re

_SAUDI_IBAN = re.compile(r'SA\d{22}')


def normalize_iban(value):
    """يزيل المسافات ويوحّد الحروف الكبيرة - الآيبان يُنسخ غالباً مقسَّماً
    بمسافات (SA03 8000 ...) من تطبيقات البنوك."""
    return re.sub(r'\s+', '', value or '').upper()


def saudi_iban_error(value):
    """رسالة الخطأ بالعربية، أو None إن كان الآيبان سليماً.

    الصيغة وحدها (SA + ٢٢ رقماً) لا تكفي: رقم التحقق الدولي (mod-97) هو ما
    يكتشف خطأ الكتابة الفعلي - رقم واحد مختلف يُنتج آيباناً بصيغة صحيحة
    تماماً لكنه لا يطابق أي حساب."""
    iban = normalize_iban(value)
    if not iban:
        return None
    if not _SAUDI_IBAN.fullmatch(iban):
        return ('رقم الآيبان "%s" غير صحيح: الآيبان السعودي يبدأ بـ SA ويليه '
                '22 رقماً (24 خانة إجمالاً، أُدخل %s).' % (value, len(iban)))
    rearranged = iban[4:] + iban[:4]
    if int(''.join(str(int(char, 36)) for char in rearranged)) % 97 != 1:
        return ('رقم الآيبان "%s" غير صحيح: رقم التحقق لا يطابق - غالباً خطأ '
                'في كتابة أحد الأرقام. راجعه مع الموظف أو تطبيق البنك.' % value)
    return None
