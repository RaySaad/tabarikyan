# -*- coding: utf-8 -*-
from odoo import fields, models


class ResCompany(models.Model):
    _inherit = 'res.company'

    # كان رقم الحساب مثبَّتاً في الكود ('212003')، وتبيّن أن الحساب
    # الفعلي 211201 - فكان قسم الرواتب والذمم في كشف الحساب يخرج فارغاً
    # بلا أي تنبيه. إعداد لأن رقم الحساب قرار محاسبي يتغيّر بتغيّر شجرة
    # الحسابات، ولا يصح أن يحتاج تعديل كود.
    settlement_dues_account_code = fields.Char(
        string='حساب ذمم الموظفين (الرقم)',
        default='211201',
        help='رقم حساب ذمم الموظفين في شجرة الحسابات - يقرأ منه كشف '
             'حساب الموظف الرواتب والعمولات وبقية الذمم. يُبحث عن الرقم '
             'في كل الشركات، فلكل فرع حسابه الخاص بالرقم نفسه.',
    )
